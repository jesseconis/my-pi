#!/usr/bin/env bash
set -euo pipefail

PACKAGE_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
MONOREPO_ROOT="$(cd "$PACKAGE_DIR/../.." && pwd)"
HOME_DIR="${HOME:?}"
VOICE_DIR="${PI_VOICE_DIR:-$HOME_DIR/.pi/voice}"
LAUNCH_AGENTS="$HOME_DIR/Library/LaunchAgents"
PLIST_PATH="$LAUNCH_AGENTS/local.pi-voice.plist"
NODE_BIN="${NODE_BIN:-$(command -v node)}"
JITI_CLI="${JITI_CLI:-$MONOREPO_ROOT/node_modules/jiti/lib/jiti-cli.mjs}"

if [ ! -f "$PACKAGE_DIR/package.json" ]; then
  echo "Missing package.json at $PACKAGE_DIR" >&2
  exit 1
fi

if [ ! -f "$JITI_CLI" ]; then
  echo "Missing jiti at $JITI_CLI" >&2
  echo "Run pnpm install at $MONOREPO_ROOT first, or set JITI_CLI." >&2
  exit 1
fi

mkdir -p "$VOICE_DIR" "$LAUNCH_AGENTS"
install -m 755 "$PACKAGE_DIR/scripts/start-pi-voice-server.sh" "$VOICE_DIR/start-pi-voice-server.sh"

if [ ! -f "$VOICE_DIR/config.json" ]; then
  install -m 600 "$PACKAGE_DIR/config/voice-config.example.json" "$VOICE_DIR/config.json"
  echo "Created $VOICE_DIR/config.json from example config. Edit it for remote backend/auth."
else
  echo "Keeping existing $VOICE_DIR/config.json"
fi

if [ ! -f "$VOICE_DIR/pronunciations.json" ]; then
  install -m 600 "$PACKAGE_DIR/config/pronunciations.example.json" "$VOICE_DIR/pronunciations.json"
  echo "Created $VOICE_DIR/pronunciations.json from example rules."
else
  echo "Keeping existing $VOICE_DIR/pronunciations.json"
fi

cat > "$VOICE_DIR/local-repo.env" <<EOF
# Generated by $PACKAGE_DIR/scripts/install-server-macos.sh
PI_VOICE_PACKAGE_DIR="$PACKAGE_DIR"
NODE_BIN="$NODE_BIN"
JITI_CLI="$JITI_CLI"
EOF

cat > "$PLIST_PATH" <<EOF
<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<plist version="1.0">
<dict>
  <key>Label</key>
  <string>local.pi-voice</string>
  <key>ProgramArguments</key>
  <array>
    <string>$VOICE_DIR/start-pi-voice-server.sh</string>
  </array>
  <key>RunAtLoad</key>
  <true/>
  <key>KeepAlive</key>
  <true/>
  <key>WorkingDirectory</key>
  <string>$PACKAGE_DIR</string>
  <key>StandardOutPath</key>
  <string>$VOICE_DIR/launchd.out.log</string>
  <key>StandardErrorPath</key>
  <string>$VOICE_DIR/launchd.err.log</string>
  <key>EnvironmentVariables</key>
  <dict>
    <key>PI_VOICE_MODEL</key>
    <string>${PI_VOICE_MODEL:-q8}</string>
  </dict>
</dict>
</plist>
EOF

launchctl bootout "gui/$(id -u)" "$PLIST_PATH" 2>/dev/null || true
launchctl bootstrap "gui/$(id -u)" "$PLIST_PATH"
launchctl kickstart -k "gui/$(id -u)/local.pi-voice"

echo "Installed local pi-voice server helper."
echo "Pi package install is separate: pi install $MONOREPO_ROOT"
echo "Health check: curl http://127.0.0.1:8181/health"
